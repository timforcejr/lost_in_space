"""
Purpose:          Write docs/RESULTS.md from the logged runs in eval/*.json so
                  that no number in the documentation is typed by hand.
Verification:     Re-run after any evaluation script; diff the output

Run:  .venv/bin/python build/make_results.py
"""
from __future__ import annotations

import json

from common import EVAL, ROOT

NAMES = {"occlusion": "Occlusion (delete a word)", "occlusion_mask": "Occlusion (mask a word)", "integrated_gradients": "Integrated gradients",
         "attention_rollout": "Attention rollout", "pair_decomposition": "Pair split",
         "grad_x_input": "Gradient × input", "token_count": "Word length only (baseline)", "random": "Random per sub-word (baseline)",
         "random_word": "Random per word (baseline)"}
DROPPED = "gradcam"    # Grad-CAM was removed from the page 2026-11-19; its rows stay in eval/*.json and are not shown here
NOTE = ("> Note: Grad-CAM (last layer) was evaluated during development (deletion gap 0.259) and removed from the page as not adding to the "
        "comparison; its numbers remain in eval/faithfulness.json.\n")
LANG = {"en": "English", "es": "Spanish", "hi": "Hindi", "zh": "Chinese"}


def load(name):
    p = EVAL / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main() -> None:
    f, f2, san, order = load("faithfulness.json"), load("faithfulness_e5.json"), load("sanity.json"), load("order.json")
    fid, place, tsne = load("map_fidelity.json"), load("placement.json"), load("tsne.json")
    gp, gb, ep = load("grad_parity.json"), load("grad_browser_parity.json"), load("export_parity.json")
    n2, n3, pc = (lambda v: f"{v:.2f}"), (lambda v: f"{v:.3f}"), (lambda v: f"{100 * v:.1f}%")
    md = ["""# Results

_Generated by `build/make_results.py` from the logged runs in `eval/*.json`; no number in it is typed by hand. The one-line readings under each table are written text: check them against the tables._
"""]
    if f:
        md.append(NOTE)
        keys = [k for k in NAMES if k in f["all"]]
        keys.sort(key=lambda k: -f["all"][k]["gap"])
        md.append(f"## 1. Which explanation is faithful? (full-precision PyTorch fp32 model)\n\n{f['n_explanations']:,} explanations of translation pairs (SIB-200 test split, English paired with Spanish, "
                  f"Hindi and Chinese, both directions; mean {f['mean_words']:.0f} words, mean similarity {f['mean_s0']:.2f}). "
                  "Words are removed in the order a method ranks them. **Gap** = share of the score kept when the least important words go "
                  "first, minus the share kept when the most important go first, averaged over 10% to 100% removed. Higher is better; a random ranking scores 0.\n")
        md.append(table(["Method", "Gap, words deleted", "95% interval", "Gap, words masked", *LANG.values()],
                        [[NAMES[k], n3(f["all"][k]["gap"]), f"{n3(f['all'][k]['gap_ci95'][0])} to {n3(f['all'][k]['gap_ci95'][1])}",
                          n3(f["mask_all"][k]["gap"]) if k in f["mask_all"] else "", *[n2(f["by_explained_language"][l][k]["gap"]) for l in LANG]] for k in keys]))
        by_n = ", ".join(f"{LANG[l]} {f['by_language_n'][l]}" for l in LANG)
        md.append(f"\nThe four language columns are the deletion gap by the language of the explained sentence "
                  f"({by_n} explanations). Chinese \"words\" are single tokenizer pieces, so its deletion word-length baseline is "
                  f"{n3(f['by_explained_language']['zh']['token_count']['gap'])} against {n3(min(f['by_explained_language'][l]['token_count']['gap'] for l in ('en', 'es', 'hi')))} to "
                  f"{n3(max(f['by_explained_language'][l]['token_count']['gap'] for l in ('en', 'es', 'hi')))} for the others; compare each language's gap with its own baseline. "
                  f"Integrated gradients' parts miss the true change in score by {n3(f['ig_completeness_abs_err_mean'])} on average "
                  f"(the change averages {n2(f['ig_target_abs_mean'])}). Occlusion by deleting and by masking rank words alike "
                  f"(mean Spearman {n2(f['occlusion_delete_vs_mask_spearman_mean'])}).\n")
        if f.get("paired_differences"):
            md.append(f"Intervals are 95% bootstrap intervals over the {f['n_sentences']} source sentences (each sentence is explained up to six "
                      "times, so whole sentences are resampled).\n")
            md.append("### Paired comparisons (same explanations, difference in gap)\n")
            pd_, pm = f["paired_differences"]["delete"], f["paired_differences"]["mask"]
            lab = lambda k: " minus ".join(NAMES.get(x, x) for x in k.split("__minus__"))
            ci = lambda v: f"{v['diff']:+.3f} ({v['ci95'][0]:+.3f} to {v['ci95'][1]:+.3f})"
            md.append(table(["Comparison", "Words deleted", "Words masked"], [[lab(k), ci(pd_[k]), ci(pm[k]) if k in pm else ""] for k in pd_ if DROPPED not in k]))
            md.append("\nAn interval that includes 0 means this benchmark finds no detectable difference between the two methods. The intervals are uncorrected for the many comparisons made.\n")
            e5p = f2 and f2.get("paired_differences")
            if e5p:
                md.append("The same comparisons on the second model (E5-small):\n")
                md.append(table(["Comparison", "Words deleted", "Words masked"], [[lab(k), ci(e5p["delete"][k]), ci(e5p["mask"][k]) if k in e5p["mask"] else ""] for k in e5p["delete"] if DROPPED not in k]))
                md.append("")
    if san:
        md.append(f"## 2. Sanity check: re-initialize the encoder layers (full-precision PyTorch fp32 model)\n\n{san['n_explanations']} explanations. The top *k* encoder layers are re-initialized; the "
                  "table is the mean Spearman correlation between a method's word ranking on the damaged model and on the trained one. "
                  "A method that describes the model should fall. \"Word length only\" ignores the model and stays at 1 by construction. "
                  "One random draw per depth, no interval. Only the encoder layers are re-initialized: the word-embedding table stays trained, "
                  "so agreement need not reach 0 even at \"all 12\".\n")
        md.append(table(["Method", *[f"top {d}" if d < 12 else "all 12" for d in san["depths"]]],
                        [[NAMES.get(m, m), *[n2(v) for v in vals]] for m, vals in san["rank_corr"].items() if DROPPED not in m]))
        md.append("\nMean similarity of the translation pairs under each model: " + ", ".join(
            f"{'trained' if k == '0' else 'top ' + k + ' random'} {n2(v)}" for k, v in san["mean_similarity"].items()) + ".\n")
    if f and f2:
        keys = [k for k in ("occlusion", "occlusion_mask", "integrated_gradients", "attention_rollout", "pair_decomposition", "grad_x_input", "token_count", "random_word")]
        md.append(f"## 3. A second model\n\nThe same benchmark on `{f2['model']}` ({f2['n_explanations']} explanations, prefix `{f2['prefix'].strip()}`; "
                  f"mean similarity {n2(f2['mean_s0'])}, so its gaps are smaller in absolute terms).\n")
        md.append(table(["Method", "This model, delete", "E5-small, delete", "This model, mask", "E5-small, mask"],
                        [[NAMES[k], n3(f["all"][k]["gap"]), n3(f2["all"][k]["gap"]), n3(f["mask_all"][k]["gap"]) if k in f["mask_all"] else "",
                          n3(f2["mask_all"][k]["gap"]) if k in f2["mask_all"] else ""] for k in keys]))
        model_based = [k for k in keys if k in ("occlusion", "occlusion_mask", "integrated_gradients", "attention_rollout", "pair_decomposition", "grad_x_input")]
        best2 = max(model_based, key=lambda k: f2["all"][k]["gap"])
        below = [NAMES[k] for k in model_based if f2["all"][k]["gap"] <= f2["all"]["token_count"]["gap"]]
        md.append(f"\nOn the second model the most faithful method is {NAMES[best2]} ({n3(f2['all'][best2]['gap'])}). "
                  f"Methods no better than ranking words by length there: {', '.join(below) if below else 'none'}. "
                  "The pair split formula assumes plain mean pooling, which both models use.")
        md.append("")
    if gp:
        md.append("## 4. Gradients in the browser\n")
        md.append(f"- Hand-written backward pass against `torch.autograd` ({gp['probe_sentences']} sentences): largest relative gradient error "
                  f"{gp['manual_vs_autograd_max']['grad_rel']:.1e}.")
        md.append(f"- Exported graph with float16-stored weights ({gp['size_mb']} MiB, {gp['size_mb'] * 2**20 / 1e6:.0f} MB decimal) against autograd: largest relative gradient error "
                  f"{100 * gp['onnx_fp16_vs_autograd_max']['grad_rel']:.2f}%, largest score error {gp['onnx_fp16_vs_autograd_max']['sim']:.1e}.")
        if gb:
            cols = ["Pair", "Words", "Score, PyTorch", "Score, browser", "Integrated gradients, Pearson r", "largest difference"]
            row = lambda p, k: [p["pair"], p["words"], n3(p[k]["sim"]), n3(p["sim_browser"]), n3(p[k]["ig_r"]), n3(p[k]["ig_d"])]
            if "worst_score_diff_gradient_vs_main_model" in gb:
                md.append(f"- Score of the gradient model against the 8-bit main model in the browser: largest difference {n3(gb['worst_score_diff_gradient_vs_main_model'])} "
                          f"over {len(gb['pairs'])} pairs. Gradients for both sentences took {gb['gradient_seconds_range'][0]:.1f} to {gb['gradient_seconds_range'][1]:.1f} s "
                          f"({gb['timing_note']}).")
            md.append("- **Implementation check.** What headless Chrome computed against PyTorch autograd *on the same inputs* (layer-0 states and the "
                      "other sentence's embedding taken from the 8-bit model, as on the page). What is left is the float16 weights, the hand-written "
                      f"backward pass and the JavaScript. Worst integrated-gradients correlation {n3(gb['worst_ig_pearson_same_inputs'])}. The two rows with the largest error are the two where the 8-bit model's own "
                      "score differs between the Python and the browser runtime (third decimal), so part of it is input difference, not gradient error.\n")
            md.append(table(cols, [row(p, "same_inputs") for p in gb["pairs"]]))
            md.append("\n- **What 8-bit weights do to an explanation.** The same browser numbers against PyTorch with everything in full precision. "
                      "The score moves by about 0.01, but for near-identical pairs the explanation moves much more: the gradient of a cosine "
                      "close to 1 is tiny, and its direction is set by the small difference between the two embeddings, which 8-bit rounding changes. "
                      f"Word-level integrated gradients differ by at most {n3(gb['worst_ig_abs_diff_full_precision'])} (of a total near 1), and on one "
                      "three-word sentence their order flips. The page explains the model it runs; this table is why the limits section says so.\n")
            md.append(table(cols, [row(p, "full_precision") for p in gb["pairs"]]))
        md.append("")
    if order:
        s, w = order["scramble"], order["paws"]
        md.append(f"## 5. Word order (full-precision PyTorch fp32 model)\n\nScramble test: {s['n_test']} held-out SIB-200 sentences in four languages (probes fitted on {s['n_train']} training "
                  f"sentences). PAWS-X: {sum(w['n_test'].values()):,} test pairs in English, Spanish and Chinese, {pc(w['paraphrase_share'])} paraphrases.\n")
        band, pr = s["cos_band_p10_p50_p90"], s["probe"]
        md.append(table(["Layer", "Similarity to the original, all words scrambled (median)", "two words swapped (median)", "Probe: natural or scrambled? (accuracy)",
                         "same probe, shuffled labels", "PAWS-X: AUC of the score", "PAWS-X: AUC of a linear probe on the pair"],
                        [[l, n3(band["shuffle"][1][l]), n3(band["swap"][1][l]), pc(pr["accuracy"][l]), pc(pr["control_accuracy"][l]),
                          n3(w["cosine_auc"]["all"][l]), n3(w["probe_auc"]["all"][l])] for l in range(order["layers"])]))
        md.append(f"\nAt the last layer the probe's accuracy by language is " + ", ".join(f"{LANG[l]} {pc(pr['by_language'][l][-1])}" for l in LANG)
                  + f". Trained on fully scrambled sentences, it detects a single swapped pair {pc(pr['swap_detect'][-1])} of the time (chance 50%). "
                  f"On PAWS-X the score averages {n2(w['cos_paraphrase'][-1])} for paraphrases and {n2(w['cos_not_paraphrase'][-1])} for non-paraphrases; "
                  "AUC by language: " + ", ".join(f"{LANG[l]} {n2(w['cosine_auc'][l][-1])}" for l in w["n_test"]) + "."
                  + (f" A richer linear probe (|a − b| and a × b) reaches AUC {n2(w['rich_probe_auc_last_layer'])}." if "rich_probe_auc_last_layer" in w else "") + "\n")
    if fid and place and tsne:
        sp = fid["spaces"]
        md.append(f"## 6. How far to trust the 3D map\n\n{fid['n_test']} held-out sentences of {fid['n_points']:,}. "
                  "Language probes are logistic regressions fitted on the training split, with the regularization strength chosen on the dev split and accuracy measured on the test split.\n")
        rows = [[name, n2(sp[k]["trust10"]), pc(place["heads"][k]["heldout_overlap10_head"]), pc(sp[k]["retrieval_p1_mean"]), pc(sp[k]["topic_knn10_acc"]), pc(sp[k]["language_probe_acc"])]
                for k, name in (("pca", "PCA"), ("fc", "FC layer"), ("ae", "Autoencoder"))]
        m = tsne["metrics"]
        rows.append(["t-SNE (fitted on all points; new sentences placed by neighbor center)", n2(m["trust10"]), pc(tsne["placement"]["heldout_overlap10_neighbour_centre"]),
                     pc(m["retrieval_p1_mean"]), pc(m["topic_knn10_acc"]), pc(m["language_probe_acc"])])
        rows.append(["Full 384 dimensions", "1.00", "100.0%", pc(sp["full_384d"]["retrieval_p1_mean"]), pc(sp["full_384d"]["topic_knn10_acc"]), pc(sp["full_384d"]["language_probe_acc"])])
        md.append(table(["Map", "Trust@10", "Top-10 neighbors kept", "Translation found", "Topic kNN", "Language probe (chance 25%)"], rows))
        lens = fid["layer_lens"]
        md.append("\n### Where the shared space forms\n")
        md.append(table(["Layer", *[str(d["layer"]) for d in lens]],
                        [["Translation pairs, cosine", *[n2(d["translation_cos"]) for d in lens]], ["Unrelated pairs, cosine", *[n2(d["random_cos"]) for d in lens]],
                         ["Language probe accuracy", *[f"{100 * d['language_probe_acc']:.0f}%" for d in lens]]]))
        md.append("")
    if ep:
        md.append(f"## 7. Browser model against PyTorch\n\n8-bit model against full precision on {ep['hidden_shape'][0]} probe sentences: lowest cosine between the two "
                  f"embeddings of a sentence {ep['cos_torch_vs_q8_min']:.4f}; largest change in a pair's similarity {ep['pair_sim_abs_err_q8_max']:.3f}.\n")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote docs/RESULTS.md", len("\n".join(md)), "chars")


if __name__ == "__main__":
    main()
